from collections import defaultdict

from odoo import _, api, fields, models
from odoo.exceptions import AccessError, UserError
from odoo.tools import float_compare

from .intercompany_transfer import GROUP_XMLID

ROLE_SCOPE = {'dispatch': 'both', 'receipt': 'dest', 'return': 'source', 'dest_return': 'dest'}


class StockPicking(models.Model):
    _inherit = 'stock.picking'

    # copy=True: native backorders and returns are created with `copy()` and
    # must stay linked to their transfer.
    intercompany_transfer_id = fields.Many2one(
        'intercompany.stock.transfer', 'Inter-Company Transfer', readonly=True, copy=True,
        index='btree_not_null', ondelete='restrict')
    intercompany_role = fields.Selection([
        ('dispatch', 'Dispatch'),
        ('receipt', 'Receipt'),
        ('return', 'Return to Source'),
        ('dest_return', 'Return from Destination'),
    ], string='Inter-Company Role', compute='_compute_intercompany_role', store=True)

    @api.depends('intercompany_transfer_id', 'company_id', 'location_id', 'location_dest_id')
    def _compute_intercompany_role(self):
        transit = self.env['intercompany.stock.transfer']._get_transit_location()
        for picking in self:
            # sudo: the role is derived from ids only and must be computable by
            # any user touching the picking.
            transfer = picking.sudo().intercompany_transfer_id
            role = False
            if transfer:
                if picking.company_id == transfer.source_company_id:
                    if picking.location_dest_id == transit:
                        role = 'dispatch'
                    elif picking.location_id == transit:
                        role = 'return'
                elif picking.company_id == transfer.dest_company_id:
                    if picking.location_id == transit:
                        role = 'receipt'
                    elif picking.location_dest_id == transit:
                        role = 'dest_return'
            picking.intercompany_role = role

    # ------------------------------------------------------------------
    # Guards
    # ------------------------------------------------------------------
    def _ict_pickings(self):
        return self.filtered(lambda p: p.sudo().intercompany_transfer_id)

    def _ict_check_access(self):
        """Operations generated by an inter-company transfer can only be
        processed by authorized users, whatever screen or API is used."""
        if self.env.su:
            return
        if not self.env.user.has_group(GROUP_XMLID):
            raise AccessError(_(
                "%s belongs to an inter-company stock transfer. Only users with the "
                "'Allow Inter-Company Stock Transfers' right can process it.",
                ', '.join(self.mapped('name'))))
        for picking in self:
            transfer = picking.sudo().intercompany_transfer_id.with_env(self.env)
            transfer._check_ict_permission(ROLE_SCOPE.get(picking.intercompany_role, 'both'))

    def _ict_get_lines_to_process(self):
        self.ensure_one()
        mls = self.move_line_ids.filtered(lambda ml: ml.quantity and ml.move_id.state not in ('done', 'cancel'))
        if any(mls.mapped('picked')):
            mls = mls.filtered('picked')
        return mls

    def _ict_check_before_done(self):
        transit = self.env['intercompany.stock.transfer']._get_transit_location()
        for picking in self:
            transfer = picking.sudo().intercompany_transfer_id
            role = picking.intercompany_role
            if transfer.state == 'draft':
                raise UserError(_("Transfer %s must be confirmed first.", transfer.name))
            mls = picking._ict_get_lines_to_process()
            if role == 'dispatch':
                if transfer.state == 'cancel':
                    raise UserError(_("Transfer %s is cancelled; it cannot be dispatched.", transfer.name))
                for ml in mls:
                    if not ml.location_id._child_of(transfer.source_location_id):
                        raise UserError(_(
                            "%(product)s must be taken from %(location)s (or one of its sub-locations).",
                            product=ml.product_id.display_name, location=transfer.source_location_id.display_name))
                    if ml.location_dest_id != transit:
                        raise UserError(_(
                            "%s must be dispatched to the inter-company transit location.",
                            ml.product_id.display_name))
                picking._ict_check_source_availability(mls)
            elif role == 'receipt':
                warehouse = transfer.dest_warehouse_id
                root = transfer.dest_location_id if warehouse.reception_steps == 'one_step' \
                    else warehouse.view_location_id
                for ml in mls:
                    if ml.location_id != transit:
                        raise UserError(_("%s must be received from the inter-company transit location.",
                                          ml.product_id.display_name))
                    if not ml.location_dest_id._child_of(root):
                        raise UserError(_(
                            "%(product)s must be received into %(location)s (or one of its sub-locations).",
                            product=ml.product_id.display_name, location=root.display_name))

    def _ict_check_source_availability(self, mls):
        """Refuse to dispatch stock that is not physically there or is reserved
        by other operations (Odoo would otherwise allow negative stock and
        steal other reservations)."""
        needs = defaultdict(float)
        for ml in mls:
            if ml.location_id.should_bypass_reservation():
                continue
            needs[(ml.product_id, ml.location_id, ml.lot_id, ml.package_id, ml.owner_id)] += ml.quantity_product_uom
        Quant = self.env['stock.quant'].sudo()
        MoveLine = self.env['stock.move.line'].sudo()
        for (product, location, lot, package, owner), need in needs.items():
            quants = Quant._gather(product, location, lot_id=lot, package_id=package, owner_id=owner, strict=True)
            on_hand = sum(quants.mapped('quantity'))
            others = MoveLine.search([
                ('product_id', '=', product.id),
                ('location_id', '=', location.id),
                ('lot_id', '=', lot.id),
                ('package_id', '=', package.id),
                ('owner_id', '=', owner.id),
                ('state', 'not in', ('done', 'cancel')),
                ('id', 'not in', mls.ids),
            ])
            available = on_hand - sum(others.mapped('quantity_product_uom'))
            if float_compare(need, available, precision_rounding=product.uom_id.rounding) > 0:
                raise UserError(_(
                    "Not enough stock to dispatch %(qty)s %(uom)s of %(product)s%(lot)s from %(location)s: "
                    "only %(available)s %(uom)s are available (on hand minus reservations of other operations).",
                    qty=need, uom=product.uom_id.name, product=product.display_name,
                    lot=lot and _(" (lot/serial %s)", lot.name) or '',
                    location=location.display_name, available=max(available, 0.0)))

    # ------------------------------------------------------------------
    # Overrides
    # ------------------------------------------------------------------
    def _action_done(self):
        ict_pickings = self._ict_pickings()
        transfers = ict_pickings.sudo().intercompany_transfer_id.with_env(self.env)
        if ict_pickings:
            ict_pickings._ict_check_access()
            transfers._lock_for_update()
            ict_pickings._ict_check_before_done()
        res = super()._action_done()
        if transfers:
            transfers._ict_after_pickings_done(ict_pickings)
        return res

    def action_cancel(self):
        ict_pickings = self._ict_pickings()
        if ict_pickings:
            ict_pickings._ict_check_access()
        res = super().action_cancel()
        if ict_pickings and not self.env.context.get('ict_skip_sync'):
            ict_pickings.sudo().intercompany_transfer_id.with_env(self.env)._sync_state()
        return res

    def unlink(self):
        if not self.env.su and self._ict_pickings():
            raise UserError(_(
                "Operations linked to an inter-company stock transfer are kept for traceability "
                "and cannot be deleted."))
        return super().unlink()

    def action_view_intercompany_transfer(self):
        self.ensure_one()
        return {
            'type': 'ir.actions.act_window',
            'res_model': 'intercompany.stock.transfer',
            'view_mode': 'form',
            'res_id': self.intercompany_transfer_id.id,
        }
